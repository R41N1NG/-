/**
 * P52_合作txt只留最近三个讨论记录.mjs —— 主人澄清：
 *   「最近三个项目，是指在合作 txt 中保留的最近三个**讨论、执行中的**项目。过往所有项目都要**保留归档**并给出索引。」
 * 落实：
 *   ① 合作.txt 里**原文照录最近三条发言**（按时间，＝最近三个讨论/执行中的项目），放在「当前保留」一节；
 *   ② 其余（更早的 27 条）**全文留在归档**（`归档/合作（归档-截至2026-10-09）.txt`），**不删**；
 *   ③ 合作.txt 保留**全部项目的索引表**（30 行：时间｜参与者｜更改项目｜完成结果）⇒ "过往所有项目给出索引"。
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = 'E:/角色卡制作/仙姝堕';
const 合作 = path.join(ROOT, 'AI交接/合作.txt');
const 归档 = path.join(ROOT, 'AI交接/归档/合作（归档-截至2026-10-09）.txt');
const 原文 = fs.readFileSync(归档, 'utf8');

const 头 = /【身份：([^｜|]+)[｜|]日期：([0-9]{4}-[0-9]{2}-[0-9]{2})[｜|]时间：([0-9:]+)[｜|]时区：([^｜|]+)[｜|]类型：([^】]+)】/g;
const 条 = [];
let m;
while ((m = 头.exec(原文)) !== null) 条.push({ 起点: m.index, 身份: m[1].trim(), 日期: m[2], 时间: m[3], 类型: m[5].replace(/\*\*/g, '').trim() });
for (let i = 0; i < 条.length; i++) 条[i].文 = 原文.slice(条[i].起点, i + 1 < 条.length ? 条[i + 1].起点 : 原文.length).trim();

const 最近 = 条.slice(-3);
const 其余数 = 条.length - 最近.length;

const 节 = [
  '',
  '## 二、当前保留（**最近三个讨论／执行中的项目**，原文照录）',
  '',
  '> 规则：本文件只保留**最近三个**讨论／执行中的项目原文；更早的 ' + 其余数 + ' 条**全文在** `归档/合作（归档-截至2026-10-09）.txt`（**一条未删**），索引见下一节。',
  '',
  ...最近.map((t) => '### ' + t.日期 + ' ' + t.时间 + '（' + (/deepseek/i.test(t.身份) ? 'deepseek' : 'gpt') + '）｜' + t.类型 + '\n\n' + t.文.replace(/^【[^】]*】\s*/, '') + '\n'),
].join('\n');

let md = fs.readFileSync(合作, 'utf8');
md = md.replace(/\n## 二、当前保留的最近三个项目（\*\*不删、不改、不搬\*\*）[\s\S]*?(?=\n## 索引口径与其它入口)/, 节);
if (!md.includes('## 二、当前保留（')) md = md.replace('\n## 索引口径与其它入口', 节 + '\n## 索引口径与其它入口');
md = md.replace(/^## 一、改动记录（时间｜参与者｜更改项目｜完成结果）$/m, '## 三、全部项目索引（含已归档项目；时间｜参与者｜更改项目｜完成结果）');
md = md.replace(/- \*\*本表覆盖\*\*：[^\n]*$/m, '- **本表覆盖**：`归档/合作（归档-截至2026-10-09）.txt` 中全部 ' + 条.length + ' 条发言（较早的 ' + 其余数 + ' 条已归档，索引在本表；最近 ' + 最近.length + ' 条的原文保留在上面第二节）。');
fs.writeFileSync(合作, md, 'utf8');

console.log('  发言总数 ' + 条.length + '｜原文保留（最近三个）：' + 最近.map((t) => t.日期 + ' ' + t.时间).join('、') + '｜归档全文：' + 其余数 + ' 条');
console.log('  已写 合作.txt：' + Math.round(fs.statSync(合作).size / 1024) + ' KB');
