      const used = new Set();
      for (const c of cast) {
        out.push(c);
        const k = xsdPersonKey(c.comment);
        const hit = minds.find((m) => !used.has(m) && (xsdPersonKey(m.comment) === k || k.includes(xsdPersonKey(m.comment))));
        if (hit) { out.push(hit); used.add(hit); }
      }
      for (const m of minds) if (!used.has(m)) out.push(m);
