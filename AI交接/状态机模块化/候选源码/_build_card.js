function normalizeEntry(comment, content) {
  let c = String(content ?? '');
  c = c.replace(/^· /gm, '- ');                       // 行首项目符号 → YAML
  /* ★★ 2026-10-07（GPT 复核定的**头号问题**）：**闸门求值报错时，条目会被保留**。
   *   本机 ST-Prompt-Template 1.17.9 源码（`dist/index.js.map` 里的 `src/function/worldinfo.ts`）：
   *     isConditionFiltedEntry() { … return (await evalTemplateHandler(`<%- !!(${arg}) %>`, …)) === 'false'; }
   *   而 `evalTemplateHandler` 出错时 catch 里打完日志就 **`return null`**（`src/utils/evaluate.ts`）。
   *   ⇒ `null === 'false'` 为假 ⇒ 「不剔除」⇒ **报错 = 闸门失效、条目照常注入**（fail-open）。
   *   `variables` 未声明时的 `ReferenceError` 同理 —— 可选链只防 `undefined.属性`，不防未声明标识符。
   *   ⇒ 这里统一把每条闸门包成**自带 try/catch 的 IIFE**：任何异常都返回 false ⇒ 条目被剔除（fail-closed）。
   *      插件会把参数再包一层 `<%- !!(( … )) %>`，所以参数本身只要是个完整表达式即可。 */
  c = c.replace(/^@@if[ \t]+([^\n]*)(\r?\n)/, (m, arg, nl) => {
    const a = String(arg).trim();
    if (/^\(function\s*\(\s*\)\s*\{\s*try\s*\{/.test(a)) return m;        // 已包过（幂等）
    return `@@if (function(){try{return (${a})}catch(e){return false}})()${nl}`;
  });
  /* ★ 2026-10-07（GPT 复核 §2）：身份判定一律**去掉 `?? '赵无忧'` 兜底**，改成严格相等 ——
   *   身份缺失时应当停止按身份分流（fail-closed），而不是被当成赵无忧放进主线。
   *   两种形态分别处理：`!==` 的要额外加「身份必须存在」，否则缺失时 `undefined !== X` 会误放行。 */
  c = c.replace(/\(variables\.stat_data\?\.身份 \?\? '赵无忧'\)\s*!==\s*([^)]+)\)/g,
    "(variables.stat_data?.身份 !== undefined && variables.stat_data?.身份 !== $1))");
  c = c.replace(/\(variables\.stat_data\?\.身份 \?\? '赵无忧'\)\s*===/g, 'variables.stat_data?.身份 ===');
  /* 〔待解锁〕前缀是 build 自己加的标记，比对分区时先剥掉 */
  const name = String(comment || '').replace(/^(\s*〔待解锁〕)+/, '');
  if (/^━+\s*【/.test(name)) return c;                 // 分区标记条：目录行，不包裹
  /* ⚠️⚠️ 2026-09-30 关键修正：`@@if` 闸门必须是**内容的第一个字符**。
   *   ST-Prompt-Template 的装饰器解析（dist `de()`）第一行就是
   *     `if (!e.startsWith("@@")) return [[], e];`   —— 内容不以 `@@` 开头 ⇒ 装饰器为空 ⇒ **整条闸门失效**。
   *   09-29 那批「用 <TAG></TAG> 包裹」把 `@@if` 挤到了第二行，结果**全卡 55 条闸门一条都不生效**：
   *   六条【身份】同时进上下文、12 条剧情闸门全开、`@@if` 那行还会作为纯文本灌进提示词
   *   （项目自己的验收口径就是「提示词里搜不到 `@@if` ＝闸门在生效」，见 `_vendor\STPT\丙-验证说明.md` §1.2／`乙-落地进展.md`）。
   *   ⇒ 做法：先把开头的 `@@…` 行原样留在最前，只把**其余正文**包进 `<TAG>`。
   *   插件求值时会把装饰器行剥掉，模型看到的仍然是 `<TAG>…</TAG>`，秋风 ③「都用 <TAG> 包裹」不受影响。 */
  const dm = /^((?:@@[^\n]*\n)+)/.exec(c);
  const head = dm ? dm[1] : '';
  const body = dm ? c.slice(head.length) : c;
  if (HAS_WRAP.test(body)) return head + body;        // 已自带外层标签（FNE 等）
  for (const [re, tag] of WRAP_BY_PREFIX) {
    if (re.test(name)) return head + `<${tag}>\n${body}\n</${tag}>`;
  }
  return c;
}
